export default function BottomNav() {
  const user   = useAppStore((s) => (s as AppStore).user)
  const unread = useAppStore((s) => (s as AppStore).unreadCount)

  if (!user) return null

  const items = NAV_ITEMS_BY_ROLE[user.role] ?? []

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-40 bg-white/95 backdrop-blur-sm border-t border-stone-100 flex safe-bottom">
      {items.map((item) => (
        <NavLink
          key={item.path}
          to={item.path}
          className={({ isActive }) =>
            cn(
              'flex-1 flex flex-col items-center justify-center py-2 gap-0.5 min-h-16 transition-colors',
              isActive ? 'text-brand-900' : 'text-stone-400',
            )
          }
        >
          {({ isActive }) => (
            <>
              <div className="relative">
                <Icon name={item.icon} active={isActive} />
                {item.icon === 'chat' && unread > 0 && (
                  <span className="absolute -top-1 -right-1 h-4 min-w-4 bg-red-500 text-white text-[9px] font-bold rounded-full flex items-center justify-center px-0.5">
                    {unread > 9 ? '9+' : unread}
                  </span>
                )}
              </div>
              <span className={cn('text-[10px] font-medium', isActive ? 'text-brand-900' : 'text-stone-400')}>
                {item.label}
              </span>
              {isActive && <span className="absolute bottom-1 w-1 h-1 bg-brand-900 rounded-full" />}
            </>
          )}
        </NavLink>
      ))}
    </nav>
  )
}

export { BottomNav }
